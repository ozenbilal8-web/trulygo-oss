export function canonicalUrl(path = "/") {
  return new URL(path, SITE_URL).toString();
}

export function serializeJsonLd(value: unknown) {
  const serialized = JSON.stringify(value);

  if (serialized === undefined) {
    throw new TypeError("JSON-LD value cannot be serialized.");
  }

  return serialized.replace(/</g, "\\u003c");
}

export function localizedAlternates(path = "/") {
  const url = canonicalUrl(path);

  return {
    canonical: url,
    languages: {
      tr: url,
    },
  };
}

export function absoluteUrl(value: string | null | undefined) {
  const url = value?.trim();

  if (!url) {
    return null;
  }

  try {
    const parsedUrl = new URL(url, SITE_URL);

    if (parsedUrl.protocol !== "http:" && parsedUrl.protocol !== "https:") {
      return null;
    }

    return parsedUrl.toString();
  } catch {
    return null;
  }
}

export function cleanSeoDescription(value: string | null | undefined, fallback: string, maxLength = 160) {
  const normalized = value?.replace(/\s+/g, " ").trim() || fallback;

  if (normalized.length <= maxLength) {
    return normalized;
  }

  const clipped = normalized.slice(0, maxLength - 1);
  const lastSpace = clipped.lastIndexOf(" ");
  const safeClip = lastSpace > 80 ? clipped.slice(0, lastSpace) : clipped;

  return `${safeClip.trim()}…`;
}
