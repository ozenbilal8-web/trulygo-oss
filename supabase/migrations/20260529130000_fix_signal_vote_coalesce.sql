-- Hotfix: Signal vote submission failed for EVERY vote in production.
--
-- Root cause
-- ----------
-- The previous migration (20260529120000_signal_vote_atomic_and_dedup.sql)
-- normalized the voter hash with:
--
--     v_normalized_hash := nullif(pg_catalog.btrim(pg_catalog.coalesce(p_voter_token_hash, '')), '');
--                                                   ^^^^^^^^^^^^^^^^^^^
--
-- COALESCE is a SQL *special expression*, not an ordinary function, so it can
-- never be schema-qualified. `pg_catalog.coalesce(...)` raises at RUNTIME:
--   "function pg_catalog.coalesce(text, unknown) does not exist".
-- check_function_bodies does not resolve this at CREATE time, so the function
-- was created successfully but threw on every invocation. Because the throw
-- happens AFTER answer validation but on every vote, the server action received
-- a generic RPC error and returned `save_failed`, which the UI shows as
-- "Cevabınız kaydedilemedi. Lütfen tekrar deneyin." — for first votes, fresh
-- browsers and brand-new surveys alike (i.e. systemic, not a dedup issue).
--
-- Note: `pg_catalog.btrim`, `pg_catalog.now`, `pg_catalog.jsonb_*` ARE real
-- catalog functions and stay qualified — only COALESCE had to become bare. This
-- matches the already-working pattern in 20260516130000_rate_limits.sql
-- (`pg_catalog.btrim(coalesce(...))`).
--
-- Fix
-- ---
-- `create or replace` the function with an IDENTICAL body except the single
-- broken line, where `pg_catalog.coalesce` becomes bare `coalesce`. Everything
-- else — atomic response+answers write, published check, per-answer
-- option->question->survey membership validation, unique_violation ->
-- 'already_voted' dedup, search_path='', SECURITY DEFINER — is preserved exactly.
--
-- The original migration file is left untouched (it is already applied in prod).
-- This migration must be applied to production (Supabase SQL Editor or CLI)
-- BEFORE deploying; no app deploy is required for the fix itself.

create or replace function public.submit_signal_vote(
  p_survey_id uuid,
  p_voter_token_hash text,
  p_answers jsonb
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status text;
  v_normalized_hash text;
  v_response_id uuid;
  v_answer jsonb;
  v_question_id uuid;
  v_option_id uuid;
begin
  -- Survey must exist and be published.
  select s.status into v_status
  from public.signal_surveys s
  where s.id = p_survey_id;

  if v_status is null then
    return 'not_found';
  end if;

  if v_status <> 'published' then
    return 'not_published';
  end if;

  -- Payload must be a non-empty JSON array.
  if p_answers is null or pg_catalog.jsonb_typeof(p_answers) <> 'array' then
    return 'invalid_answer';
  end if;

  if pg_catalog.jsonb_array_length(p_answers) = 0 then
    return 'empty';
  end if;

  -- Validate every answer: the option must exist, belong to the given question,
  -- and that question must belong to this survey.
  for v_answer in
    select e.value
    from pg_catalog.jsonb_array_elements(p_answers) as e(value)
  loop
    begin
      v_question_id := (v_answer ->> 'question_id')::uuid;
      v_option_id := (v_answer ->> 'option_id')::uuid;
    exception
      when others then
        return 'invalid_answer';
    end;

    if v_question_id is null or v_option_id is null then
      return 'invalid_answer';
    end if;

    if not exists (
      select 1
      from public.signal_options o
      join public.signal_questions q on q.id = o.question_id
      where o.id = v_option_id
        and o.question_id = v_question_id
        and q.survey_id = p_survey_id
    ) then
      return 'invalid_answer';
    end if;
  end loop;

  -- Treat blank hashes as null so the partial unique index ignores them.
  -- NOTE: coalesce() must stay bare; it is a SQL special expression and cannot
  -- be schema-qualified (this was the production bug). btrim is a real catalog
  -- function and stays qualified.
  v_normalized_hash := nullif(pg_catalog.btrim(coalesce(p_voter_token_hash, '')), '');

  -- Insert the response. A repeat vote trips the partial unique index; we map
  -- that to 'already_voted' rather than surfacing a constraint error. The id is
  -- generated by the table default.
  begin
    insert into public.signal_responses (survey_id, voter_token_hash, completed_at)
    values (p_survey_id, v_normalized_hash, pg_catalog.now())
    returning id into v_response_id;
  exception
    when unique_violation then
      return 'already_voted';
  end;

  -- Insert every answer in the same transaction. Validation above guarantees the
  -- option/question FK is satisfied, so this cannot leave an orphan response: any
  -- unexpected failure rolls back the response insert too.
  insert into public.signal_answers (response_id, survey_id, question_id, option_id)
  select
    v_response_id,
    p_survey_id,
    (e.value ->> 'question_id')::uuid,
    (e.value ->> 'option_id')::uuid
  from pg_catalog.jsonb_array_elements(p_answers) as e(value);

  return 'ok';
end;
$$;

revoke all on function public.submit_signal_vote(uuid, text, jsonb) from public;
grant execute on function public.submit_signal_vote(uuid, text, jsonb) to anon, authenticated;
